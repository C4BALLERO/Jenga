        static GameObject CreatePlayerPrefab(WeaponData starter, Dictionary<string, ItemData> items)
        {
            var root = new GameObject("Player");
            root.layer = LayerPlayer;
            root.tag = "Player";

            var cc = root.AddComponent<CharacterController>();
            cc.height = 1.8f;
            cc.radius = 0.35f;
            cc.center = new Vector3(0f, 0.9f, 0f);
            cc.slopeLimit = 50f;
            cc.stepOffset = 0.4f;

            var pivot = ModelFactory.Empty("CameraPivot", root.transform, new Vector3(0f, 1.65f, 0f));
            var camGo = new GameObject("PlayerCamera");
            camGo.transform.SetParent(pivot, false);
            camGo.tag = "MainCamera";
            var cam = camGo.AddComponent<Camera>();
            cam.fieldOfView = 72f;
            cam.nearClipPlane = 0.03f;
            cam.farClipPlane = 400f;
            camGo.AddComponent<AudioListener>();

            var socket = ModelFactory.Empty("WeaponSocket", camGo.transform, Vector3.zero);
            socket.gameObject.layer = LayerPlayer;

            var controller = root.AddComponent<PlayerController>();
            var health = root.AddComponent<PlayerHealth>();
            var inventory = root.AddComponent<PlayerInventory>();
            var wallet = root.AddComponent<Wallet>();
            var equipment = root.AddComponent<PlayerEquipment>();
            var weapon = root.AddComponent<WeaponController>();
            var loadout = root.AddComponent<StartingLoadout>();

            FieldWriter.On(controller).Ref("cameraPivot", pivot).Apply();
            FieldWriter.On(health).Float("maxHealth", 120f).Float("regenPerSecond", 3f).Float("regenDelay", 5f).Apply();
            FieldWriter.On(inventory).Int("slotCount", 24).Apply();
            FieldWriter.On(wallet).Int("money", 250).Apply();
            FieldWriter.On(equipment).Ref("weaponSocket", socket).Ref("startingWeapon", starter).Apply();
            FieldWriter.On(weapon)
                .Ref("aimCamera", cam)
                .Mask("hitMask", ~((1 << LayerPlayer) | (1 << LayerLoot)))
                .Apply();

            // Objetos iniciales.
            var so = new SerializedObject(loadout);
            var entries = so.FindProperty("entries");
            var startItems = new (ItemData item, int amount)[]
            {
                (starter, 1),
                (items["medkit"], 2),
                (items["ammo"], 1),
                (items["scrap"], 3),
            };
            entries.arraySize = startItems.Length;
            for (int i = 0; i < startItems.Length; i++)
            {
                var e = entries.GetArrayElementAtIndex(i);
                e.FindPropertyRelative("item").objectReferenceValue = startItems[i].item;
                e.FindPropertyRelative("amount").intValue = startItems[i].amount;
            }
            so.ApplyModifiedPropertiesWithoutUndo();

            return SavePrefab(root, $"{PrefabsFolder}/Player.prefab");
        }

        static void SetLayerRecursive(GameObject go, int layer)
        {
            go.layer = layer;
            foreach (Transform child in go.transform) SetLayerRecursive(child.gameObject, layer);
        }

