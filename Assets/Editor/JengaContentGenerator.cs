        [MenuItem("Jenga/Generar contenido del juego", priority = 0)]
        public static void GenerateFromMenu()
        {
            bool exists = AssetDatabase.LoadAssetAtPath<GameDatabase>(DatabasePath) != null;
            if (exists && !EditorUtility.DisplayDialog(
                    "Regenerar contenido",
                    "Se volverán a crear los assets generados (iconos, materiales, prefabs, objetos, enemigos, oleadas y la escena Game.unity).\n\nSe perderán los ajustes manuales hechos sobre esos assets.",
                    "Regenerar", "Cancelar"))
                return;

            Generate(true);
        }

        [MenuItem("Jenga/Abrir escena de juego", priority = 1)]
        public static void OpenGameScene()
        {
            if (!File.Exists(ScenePath))
            {
                if (EditorUtility.DisplayDialog("Escena no encontrada",
                        "Todavía no se ha generado la escena. ¿Generar el contenido ahora?", "Generar", "Cancelar"))
                    Generate(true);
                return;
            }
            if (EditorSceneManager.SaveCurrentModifiedScenesIfUserWantsTo())
                EditorSceneManager.OpenScene(ScenePath);
        }

        const string AutoRunKey = "Jenga.AutoGenerated";
        static int _framesWaited;

        /// <summary>
        /// Primera vez que se abre el proyecto: crea el contenido si aún no existe.
        /// Se espera unos frames en vez de usar EditorApplication.delayCall porque ese
        /// callback es un delegado multicast: si otro sistema del editor lanza una
        /// excepción antes (por ejemplo el indexador de UnityEditor.Search), el resto
        /// de la cadena no llega a ejecutarse y la generación se quedaría sin hacer.
        /// </summary>
        [InitializeOnLoadMethod]
        static void AutoGenerateOnFirstLoad()
        {
            if (SessionState.GetBool(AutoRunKey, false)) return;
            _framesWaited = 0;
            EditorApplication.update -= WaitForIdleThenGenerate;
            EditorApplication.update += WaitForIdleThenGenerate;
        }

        static void WaitForIdleThenGenerate()
        {
            // Deja que el editor termine de importar, compilar e indexar.
            if (EditorApplication.isCompiling || EditorApplication.isUpdating) return;
            if (++_framesWaited < 30) return;

            EditorApplication.update -= WaitForIdleThenGenerate;

            if (EditorApplication.isPlayingOrWillChangePlaymode) return;
            if (SessionState.GetBool(AutoRunKey, false)) return;
            SessionState.SetBool(AutoRunKey, true);
            if (AssetDatabase.LoadAssetAtPath<GameDatabase>(DatabasePath) != null) return;

            try
            {
                Debug.Log("[Jenga] Generando el contenido del juego por primera vez...");
                Generate(false);
            }
            catch (System.Exception e)
            {
                Debug.LogError("[Jenga] Falló la generación automática. Usa el menú " +
                               "Jenga > Generar contenido del juego para reintentarlo.\n" + e);
            }
        }

        public static void Generate(bool openScene)
        {
            try
            {
                EditorUtility.DisplayProgressBar("Jenga", "Creando carpetas...", 0f);
                EnsureFolders();

                EditorUtility.DisplayProgressBar("Jenga", "Dibujando sprites...", 0.1f);
                _icons = IconPainter.GenerateAll(IconsFolder);

                EditorUtility.DisplayProgressBar("Jenga", "Creando materiales...", 0.25f);
                _materials = CreateMaterials();

                EditorUtility.DisplayProgressBar("Jenga", "Construyendo modelos y prefabs...", 0.4f);
                var weaponModels = CreateWeaponModels();
                var lootPrefab = CreateLootPrefab();

                EditorUtility.DisplayProgressBar("Jenga", "Creando objetos y armas...", 0.55f);
                var items = CreateItems();
                var weapons = CreateWeapons(weaponModels);

                EditorUtility.DisplayProgressBar("Jenga", "Creando enemigos y oleadas...", 0.7f);
                var enemies = CreateEnemies(items);
                var waveConfig = CreateWaveConfig(enemies);
                var shopStock = CreateShopStock(items, weapons);

                EditorUtility.DisplayProgressBar("Jenga", "Creando el jugador...", 0.8f);
                var playerPrefab = CreatePlayerPrefab(weapons["pistol"], items);

                EditorUtility.DisplayProgressBar("Jenga", "Guardando la base de datos...", 0.88f);
                var database = CreateDatabase(items, weapons, enemies, waveConfig, lootPrefab);

                EditorUtility.DisplayProgressBar("Jenga", "Montando la escena...", 0.94f);
                BuildScene(playerPrefab, database, waveConfig, shopStock, openScene);

                AssetDatabase.SaveAssets();
                AssetDatabase.Refresh();
                Debug.Log("[Jenga] Contenido generado. Abre Assets/Scenes/Game.unity y pulsa Play.");
            }
            finally
            {
                EditorUtility.ClearProgressBar();
            }
        }

        // ------------------------------------------------------------ carpetas

        static void EnsureFolders()
        {
            string[] folders =
            {
                Root, IconsFolder, MaterialsFolder, PrefabsFolder, ItemsFolder,
                EnemiesFolder, ConfigFolder, ResourcesFolder, "Assets/Scenes"
            };
            foreach (var f in folders)
            {
                if (AssetDatabase.IsValidFolder(f)) continue;
                Directory.CreateDirectory(f);
            }
            AssetDatabase.Refresh();
        }

        static T CreateOrReplace<T>(string path) where T : ScriptableObject
        {
            var existing = AssetDatabase.LoadAssetAtPath<T>(path);
            if (existing != null) return existing;
            var asset = ScriptableObject.CreateInstance<T>();
            AssetDatabase.CreateAsset(asset, path);
            return asset;
        }

