        static GameObject BuildEnemyPrefab(EnemyData data, string prefabName, float colliderHeight, float colliderRadius, bool runner)
        {
            var root = new GameObject(prefabName);
            root.layer = LayerEnemy;

            var collider = root.AddComponent<CapsuleCollider>();
            collider.height = colliderHeight;
            collider.radius = colliderRadius;
            collider.center = Vector3.zero;

            var rb = root.AddComponent<Rigidbody>();
            rb.isKinematic = true;
            rb.useGravity = false;

            var visual = runner
                ? ModelFactory.BuildRunnerBody(root.transform, _materials["enemy"], _materials["enemyDark"], _materials["accent"])
                : ModelFactory.BuildGruntBody(root.transform, _materials["enemy"], _materials["enemyDark"], _materials["accent"]);
            SetLayerRecursive(root, LayerEnemy);

            var enemy = root.AddComponent<Enemy>();
            var renderers = new List<Renderer>();
            foreach (var r in visual.GetComponentsInChildren<Renderer>())
                if (r.sharedMaterial == _materials["enemy"]) renderers.Add(r);

            FieldWriter.On(enemy)
                .Ref("data", data)
                .Ref("visualRoot", visual.transform)
                .RefList("bodyRenderers", renderers)
                .Mask("groundMask", 1)
                .Apply();

            return SavePrefab(root, $"{PrefabsFolder}/{prefabName}.prefab");
        }

