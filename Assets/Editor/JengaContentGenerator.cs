        static void BuildScene(GameObject playerPrefab, GameDatabase database, WaveConfig waveConfig, ShopStock shopStock, bool openScene)
        {
            var previous = SceneManager.GetActiveScene();
            var scene = EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Additive);
            SceneManager.SetActiveScene(scene);

            // Iluminación.
            var lightGo = new GameObject("Directional Light");
            var light = lightGo.AddComponent<Light>();
            light.type = LightType.Directional;
            light.intensity = 1.15f;
            light.color = new Color(1f, 0.96f, 0.88f);
            light.shadows = LightShadows.Soft;
            lightGo.transform.rotation = Quaternion.Euler(48f, -35f, 0f);

            RenderSettings.ambientMode = UnityEngine.Rendering.AmbientMode.Trilight;
            RenderSettings.ambientSkyColor = new Color(0.35f, 0.42f, 0.55f);
            RenderSettings.ambientEquatorColor = new Color(0.22f, 0.24f, 0.30f);
            RenderSettings.ambientGroundColor = new Color(0.10f, 0.10f, 0.12f);
            RenderSettings.fog = true;
            RenderSettings.fogMode = FogMode.Linear;
            RenderSettings.fogColor = new Color(0.13f, 0.15f, 0.19f);
            RenderSettings.fogStartDistance = 45f;
            RenderSettings.fogEndDistance = 160f;
            var skybox = AssetDatabase.GetBuiltinExtraResource<Material>("Default-Skybox.mat");
            if (skybox != null) RenderSettings.skybox = skybox;

            // Arena.
            var arena = new GameObject("Arena");
            ModelFactory.Part("Ground", PrimitiveType.Cube, arena.transform, new Vector3(0f, -0.5f, 0f), new Vector3(70f, 1f, 70f), _materials["ground"]);
            arena.transform.Find("Ground").gameObject.AddComponent<BoxCollider>();

            float half = 35f;
            CreateWall(arena.transform, new Vector3(0f, 2f, half), new Vector3(70f, 4f, 1f));
            CreateWall(arena.transform, new Vector3(0f, 2f, -half), new Vector3(70f, 4f, 1f));
            CreateWall(arena.transform, new Vector3(half, 2f, 0f), new Vector3(1f, 4f, 70f));
            CreateWall(arena.transform, new Vector3(-half, 2f, 0f), new Vector3(1f, 4f, 70f));

            // Coberturas.
            var rng = new System.Random(7);
            for (int i = 0; i < 14; i++)
            {
                float angle = (float)(rng.NextDouble() * Mathf.PI * 2f);
                float radius = 8f + (float)rng.NextDouble() * 20f;
                var pos = new Vector3(Mathf.Cos(angle) * radius, 0f, Mathf.Sin(angle) * radius);
                var size = new Vector3(1.5f + (float)rng.NextDouble() * 3f, 1f + (float)rng.NextDouble() * 2.5f, 1.5f + (float)rng.NextDouble() * 3f);
                var block = ModelFactory.Part($"Cover_{i}", PrimitiveType.Cube, arena.transform,
                    pos + Vector3.up * (size.y * 0.5f), size, _materials["cover"],
                    new Vector3(0f, (float)rng.NextDouble() * 90f, 0f));
                block.AddComponent<BoxCollider>();
            }

            // Marcas del suelo.
            ModelFactory.Part("Plaza", PrimitiveType.Cylinder, arena.transform, new Vector3(0f, 0.01f, 0f), new Vector3(18f, 0.01f, 18f), _materials["grid"]);

            // Tienda.
            var kiosk = ModelFactory.BuildShopKiosk(_materials["wall"], _materials["gunDark"], _materials["accent"], _materials["wood"]);
            kiosk.transform.position = new Vector3(0f, 0f, 12f);
            kiosk.transform.rotation = Quaternion.Euler(0f, 180f, 0f);
            var kioskCollider = kiosk.transform.Find("Base").gameObject.AddComponent<BoxCollider>();
            kioskCollider.enabled = true;
            var shopZone = kiosk.AddComponent<ShopZone>();
            FieldWriter.On(shopZone)
                .Float("radius", 6f)
                .Ref("visual", kiosk.transform.Find("Hologram"))
                .Apply();

            // Puntos de aparición.
            var spawnRoot = new GameObject("SpawnPoints");
            var spawnPoints = new List<Transform>();
            for (int i = 0; i < 10; i++)
            {
                float angle = i / 10f * Mathf.PI * 2f;
                var go = new GameObject($"Spawn_{i}");
                go.transform.SetParent(spawnRoot.transform, false);
                go.transform.position = new Vector3(Mathf.Cos(angle), 0f, Mathf.Sin(angle)) * 27f + Vector3.up;
                spawnPoints.Add(go.transform);
            }

            // Jugador.
            var player = (GameObject)PrefabUtility.InstantiatePrefab(playerPrefab, scene);
            player.transform.position = new Vector3(0f, 0.2f, -4f);
            var playerController = player.GetComponent<PlayerController>();

            // Sistemas.
            var systems = new GameObject("GameSystems");
            var gameManager = systems.AddComponent<GameManager>();
            FieldWriter.On(gameManager).Ref("database", database).Ref("player", playerController).Apply();

            var waveManager = systems.AddComponent<WaveManager>();
            FieldWriter.On(waveManager)
                .Ref("config", waveConfig)
                .RefList("spawnPoints", spawnPoints)
                .Ref("arenaCenter", arena.transform)
                .Float("fallbackSpawnRadius", 27f)
                .Apply();

            var shopController = systems.AddComponent<ShopController>();
            FieldWriter.On(shopController)
                .Ref("stock", shopStock)
                .Ref("inventory", player.GetComponent<PlayerInventory>())
                .Ref("wallet", player.GetComponent<Wallet>())
                .Apply();

            // Interfaz.
            var uiGo = new GameObject("GameUI");
            var gameUi = uiGo.AddComponent<GameUI>();
            FieldWriter.On(gameUi).Ref("player", playerController).Apply();

            EditorSceneManager.MarkSceneDirty(scene);
            EditorSceneManager.SaveScene(scene, ScenePath);

            AddSceneToBuildSettings(ScenePath);

            bool previousValid = previous.IsValid() && previous != scene;
            bool canOpen = openScene || (previousValid && !previous.isDirty);
            if (previousValid) SceneManager.SetActiveScene(previous);
            EditorSceneManager.CloseScene(scene, true);

            if (canOpen && EditorSceneManager.SaveCurrentModifiedScenesIfUserWantsTo())
                EditorSceneManager.OpenScene(ScenePath);
        }

        static void CreateWall(Transform parent, Vector3 position, Vector3 size)
        {
            var wall = ModelFactory.Part("Wall", PrimitiveType.Cube, parent, position, size, _materials["wall"]);
            wall.AddComponent<BoxCollider>();
        }

        static void AddSceneToBuildSettings(string path)
        {
            var scenes = new List<EditorBuildSettingsScene>(EditorBuildSettings.scenes);
            foreach (var s in scenes)
                if (s.path == path) return;
            scenes.Insert(0, new EditorBuildSettingsScene(path, true));
            EditorBuildSettings.scenes = scenes.ToArray();
        }
