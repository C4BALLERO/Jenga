        static Dictionary<string, GameObject> CreateWeaponModels()
        {
            var result = new Dictionary<string, GameObject>();
            var body = _materials["gunBody"];
            var dark = _materials["gunDark"];
            var accent = _materials["accent"];
            var wood = _materials["wood"];

            result["pistol"] = SavePrefab(ModelFactory.BuildPistol(body, dark, accent), $"{PrefabsFolder}/Model_Pistol.prefab");
            result["rifle"] = SavePrefab(ModelFactory.BuildRifle(body, dark, accent), $"{PrefabsFolder}/Model_Rifle.prefab");
            result["shotgun"] = SavePrefab(ModelFactory.BuildShotgun(body, dark, wood), $"{PrefabsFolder}/Model_Shotgun.prefab");
            return result;
        }

        static GameObject SavePrefab(GameObject instance, string path)
        {
            var prefab = PrefabUtility.SaveAsPrefabAsset(instance, path);
            Object.DestroyImmediate(instance);
            return prefab;
        }

        static GameObject CreateLootPrefab()
        {
            var root = new GameObject("LootPickup");
            root.layer = LayerLoot;

            var spin = ModelFactory.Empty("Spin", root.transform, new Vector3(0f, 0.35f, 0f));

            var iconGo = new GameObject("Icon");
            iconGo.transform.SetParent(spin, false);
            iconGo.transform.localScale = Vector3.one * 0.75f;
            iconGo.layer = LayerLoot;
            var sr = iconGo.AddComponent<SpriteRenderer>();
            sr.sprite = _icons["icon_coin"];
            iconGo.AddComponent<Billboard>();

            ModelFactory.Part("Glow", PrimitiveType.Sphere, spin, Vector3.zero, Vector3.one * 0.16f, _materials["accent"]);
            ModelFactory.Part("Ring", PrimitiveType.Cylinder, root.transform, new Vector3(0f, 0.02f, 0f), new Vector3(0.55f, 0.02f, 0.55f), _materials["accent"]);

            var drop = root.AddComponent<LootDrop>();
            FieldWriter.On(drop)
                .Ref("iconRenderer", sr)
                .Ref("spinRoot", spin)
                .Apply();

            return SavePrefab(root, $"{PrefabsFolder}/LootPickup.prefab");
        }

